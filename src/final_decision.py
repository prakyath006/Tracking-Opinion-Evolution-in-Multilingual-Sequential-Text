"""
Final decision / summary module.

Combines outputs that already exist (OET sentiments, transitions and trajectory, the aspect-associated
projection of aspect_sentiment.py, and any model scores) into one JSON-serialisable summary with a
verdict sentence. Every statement is produced by the fixed rules below; nothing is scored, weighted
or generated by a language model, and scores from different modules are never averaged together.
"""
from typing import Dict, List, Optional, Sequence

from aspect_sentiment import aspect_sentiment_projection, tag_messages
from ontology import SentimentState, TrajectoryType, TransitionType

NO_TURNING_POINT = "No turning point detected"
_SENT, _TRANS, _TRAJ = (set(e.label_names()) for e in (SentimentState, TransitionType, TrajectoryType))
_OPPOSITE = {"UPGRADE": "DOWNGRADE", "DOWNGRADE": "UPGRADE"}


def detect_turning_points(transitions: Sequence[str]) -> Dict:
    """
    transitions[k] is the transition from message k+1 to message k+2 (1-based messages).

    A turning point is a direction reversal: a directional transition (UPGRADE or DOWNGRADE) followed,
    as the next directional transition, by the opposite one. STABLE transitions carry no direction:
    they neither create a reversal nor cancel one, so UPGRADE, STABLE, DOWNGRADE is one reversal and
    UPGRADE, STABLE, STABLE is none. The reported position is the message at which the reversing
    transition starts, i.e. the last message before the opinion moved the other way.
    """
    for t in transitions:
        if t not in _TRANS:
            raise ValueError(f"invalid transition label {t!r}; expected one of {sorted(_TRANS)}")
    reversals, last = [], None                               # last = (index, label) of the previous directional step
    for k, t in enumerate(transitions):
        if t == "STABLE":
            continue
        if last and t == _OPPOSITE[last[1]]:
            reversals.append({
                "position": k + 1,
                "before": {"transition": last[1], "from_message": last[0] + 1, "to_message": last[0] + 2},
                "after": {"transition": t, "from_message": k + 1, "to_message": k + 2},
            })
        last = (k, t)
    if not reversals:
        return {"found": False, "position": None, "count": 0, "reversals": [], "message": NO_TURNING_POINT}
    first = reversals[0]
    msg = (f"Direction reversal after message {first['position']}: {first['before']['transition']} "
           f"(message {first['before']['from_message']} to {first['before']['to_message']}) was followed by "
           f"{first['after']['transition']} (message {first['after']['from_message']} to {first['after']['to_message']}).")
    if len(reversals) > 1:
        msg += f" {len(reversals)} reversals in total."
    return {"found": True, "position": first["position"], "count": len(reversals), "reversals": reversals, "message": msg}


def _pretty(aspect: str) -> str:
    return aspect.replace("_", " ")


def final_decision(sentiments: Sequence[str], transitions: Sequence[str], trajectory: str,
                   aspect_summary: Optional[Dict] = None, confidence: Optional[Dict] = None,
                   attention: Optional[Sequence[float]] = None) -> Dict:
    """
    sentiments      predicted label per message (ontology names)
    transitions     predicted transition per consecutive pair (len(sentiments) - 1 entries)
    trajectory      predicted trajectory for the sequence
    aspect_summary  output of aspect_sentiment_projection(), or None
    confidence      {source name: value}; each entry is reported as given, under its own name
    attention       OET attention weight per message (a weight, not a probability)
    """
    sentiments, transitions = list(sentiments), list(transitions)
    if not sentiments:
        raise ValueError("at least one message-level sentiment is required")
    bad = [s for s in sentiments if s not in _SENT]
    if bad:
        raise ValueError(f"invalid sentiment label(s) {bad}; expected one of {sorted(_SENT)}")
    if trajectory not in _TRAJ:
        raise ValueError(f"invalid trajectory label {trajectory!r}; expected one of {sorted(_TRAJ)}")
    if len(transitions) != len(sentiments) - 1:
        raise ValueError("transitions must have exactly len(sentiments) - 1 entries")
    if attention is not None and len(attention) != len(sentiments):
        raise ValueError("attention must have one weight per message")

    n = len(sentiments)
    turning = detect_turning_points(transitions)
    distribution = {name: sentiments.count(name) for name in SentimentState.label_names()}
    # Cross-check between heads: the trajectory the ontology rule gives for the predicted sentiments.
    rule_trajectory = TrajectoryType.compute([SentimentState[s] for s in sentiments]).name if n >= 2 else None

    aspects = list((aspect_summary or {}).get("aspects", {}).values())
    important = [{"aspect": a["aspect"], "occurrences": a["occurrences"], "n_messages": a["n_messages"],
                  "tendency": a["tendency"], "trend": a["trend"], "trend_note": a["trend_note"],
                  # An aspect trend can only be compared with the trajectory when it exists.
                  "vs_trajectory": ("not comparable" if a["trend"] is None
                                    else "agrees" if a["trend"] == trajectory else "differs")}
                 for a in aspects[:3]]                       # projection output is already ordered by frequency
    comparable = [a for a in important if a["vs_trajectory"] != "not comparable"]
    if not comparable:
        agreement = "not assessable"
    elif all(a["vs_trajectory"] == "agrees" for a in comparable):
        agreement = "agreement"
    else:
        agreement = "disagreement"

    limits = []
    if n < 3:
        limits.append(f"only {n} message(s): a reversal needs at least 3")
    if n < 2:
        limits.append("a single message has no transition, so the trajectory is not informative")
    if not aspects:
        limits.append("no aspect was detected, so there is no aspect-associated evidence")
    elif not comparable:
        limits.append("no aspect has two or more sentiment observations, so no aspect trend exists")
    if rule_trajectory and rule_trajectory != trajectory:
        limits.append(f"the trajectory head predicts {trajectory} but the ontology rule applied to the "
                      f"predicted sentiments gives {rule_trajectory}")
    if not confidence:
        limits.append("no model confidence value was supplied")

    parts = [f"Overall trajectory: {trajectory.capitalize()}."]
    parts.append(turning["message"] if turning["found"] else NO_TURNING_POINT + ".")
    if important:
        top = important[0]
        tend = (f"predominantly {top['tendency'].lower()} associated message sentiment" if top["tendency"]
                else "no dominant associated message sentiment")
        parts.append(f"The most frequently identified aspect was {_pretty(top['aspect'])} "
                     f"({top['n_messages']} of {n} messages), with {tend}.")
        if top["trend"]:
            parts.append(f"Its associated sentiment trend is {top['trend'].lower()}, which "
                         f"{'agrees with' if top['vs_trajectory'] == 'agrees' else 'differs from'} the overall trajectory.")
        else:
            parts.append(f"Aspect trend: {top['trend_note']}.")
    else:
        parts.append("No aspect was identified in these messages.")
    n_obs = sum(a["n_messages"] for a in aspects)
    parts.append(f"Evidence: {n} message(s), {len(transitions)} transition(s), {n_obs} aspect observation(s).")
    if limits:
        parts.append("The conclusion is limited: " + "; ".join(limits) + ".")

    out = {
        "trajectory": trajectory,
        "rule_derived_trajectory_from_predicted_sentiments": rule_trajectory,
        "sentiment_distribution": distribution,
        "turning_point": turning,
        "important_aspects": important,
        "trajectory_vs_aspect_evidence": agreement,
        "confidence": dict(confidence) if confidence else None,
        "confidence_note": ("Each value is reported by its own source and is not a calibrated probability; "
                            "values are not combined." if confidence else "not available"),
        "evidence": {
            "n_messages": n, "n_transitions": len(transitions), "n_aspect_observations": n_obs,
            "aspect_message_coverage": (aspect_summary or {}).get("message_coverage"),
            "limited": bool(limits), "limitations": limits,
        },
        "verdict": " ".join(parts),
    }
    if attention is not None:
        weights = [float(w) for w in attention]
        out["most_attended_message"] = {"position": weights.index(max(weights)) + 1, "attention_weight": max(weights),
                                        "note": "attention weight of the trajectory head, not a probability"}
    return out


def oet_outputs(model, texts: List[str]) -> Dict:
    """
    One OET forward pass on one sequence, returned as label names plus the softmax score of each
    predicted class. The labels are the same argmax that OpinionEvolutionTracker.predict() returns.
    Position 0 of the trend head is a placeholder (no previous message), so transitions start at 1.
    """
    import torch
    model.eval()
    with torch.no_grad():
        out = model.forward([texts])
    n = len(texts)
    sent_p = out["sentiment_logits"][0][:n].softmax(-1)
    trend_p = out["trend_logits"][0][:n].softmax(-1)
    traj_p = out["trajectory_logits"][0].softmax(-1)
    s_names, t_names, j_names = (e.label_names() for e in (SentimentState, TransitionType, TrajectoryType))
    return {
        "sentiments": [s_names[i] for i in sent_p.argmax(-1).tolist()],
        "sentiment_softmax": [round(v, 4) for v in sent_p.max(-1).values.tolist()],
        "transitions": [t_names[i] for i in trend_p.argmax(-1).tolist()[1:]],
        "transition_softmax": [round(v, 4) for v in trend_p.max(-1).values.tolist()[1:]],
        "trajectory": j_names[int(traj_p.argmax())],
        "trajectory_softmax": round(float(traj_p.max()), 4),
        "attention": [round(v, 4) for v in out["attention_weights"][0][:n].tolist()],
    }


def run_pipeline(messages: Sequence[str], oet: Optional[Dict], wsd=None) -> Dict:
    """
    End-to-end integration: WSD aspect tags -> aspect-associated projection -> final decision.
    `oet` is the dict from oet_outputs(), or None when no compatible sentiment model exists for the
    input; then aspects are reported without sentiment and no decision is produced.
    """
    messages = list(messages)
    tags = tag_messages(messages, wsd) if wsd is not None else None
    aspects = aspect_sentiment_projection(messages, oet["sentiments"] if oet else None, tags,
                                          oet.get("sentiment_softmax") if oet else None)
    result = {"messages": messages, "oet": oet, "aspect_analysis": aspects, "final_decision": None}
    if oet:
        result["final_decision"] = final_decision(
            oet["sentiments"], oet["transitions"], oet["trajectory"], aspects,
            confidence={"oet_trajectory_softmax (uncalibrated)": oet["trajectory_softmax"],
                        "oet_sentiment_softmax_per_message (uncalibrated)": oet["sentiment_softmax"]},
            attention=oet["attention"])
    return result
